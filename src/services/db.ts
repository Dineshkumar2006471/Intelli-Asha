/** Listen to real-time updates for District AI Analytics generated by Analytics Agent */
export function onAnalyticsSnapshot(location: string, callback: (data: any) => void): Unsubscribe {
  const analyticsRef = doc(db, 'analytics', location);
  
  return onSnapshot(analyticsRef, (snapshot) => {
    if (snapshot.exists()) {
      callback(snapshot.data());
    } else {
      callback(null);
    }
  });
}

