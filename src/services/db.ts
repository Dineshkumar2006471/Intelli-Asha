import { db, functions } from '../firebase';
import { httpsCallable } from 'firebase/functions';
import {
  collection,
  addDoc,
  doc,
  setDoc,
  getDocs,
  query,
  where,
  orderBy,
  serverTimestamp,
  limit,
  onSnapshot,
  type Unsubscribe,
} from 'firebase/firestore';
import type { Visit, VisitData, Alert, GeoAnchor, DashboardMetrics, AgentLog } from '../types';
import { createLogger } from '../utils/logger';

const log = createLogger('DB');

// ---------------------------------------------------------------------------
// Writes
// ---------------------------------------------------------------------------

/** Saves a completed visit to Firestore. Alerts are created by the backend Verification Agent. */
export async function saveVisit(
  visitData: VisitData & { rawTranscription: string; geoAnchor: GeoAnchor | null; audioUrl?: string | null; locationName?: string; districtName?: string },
  userId: string
): Promise<string> {
  try {
    const visitsRef = collection(db, 'visits');
    const docRef = await addDoc(visitsRef, {
      ...visitData,
      workerId: userId,
      timestamp: serverTimestamp(),
    });
    log.info('Visit saved successfully', { visitId: docRef.id, household: visitData.householdName });
    return docRef.id;
  } catch (error) {
    log.error('Failed to save visit', error);
    throw error;
  }
}

/** Updates an existing visit in Firestore (e.g., marking as resolved). */
export async function updateVisit(
  visitId: string,
  data: Partial<Visit>
): Promise<void> {
  try {
    const visitRef = doc(db, 'visits', visitId);
    await setDoc(visitRef, data, { merge: true });
    log.info('Visit updated successfully', { visitId });
  } catch (error) {
    log.error('Failed to update visit', error);
    throw error;
  }
}


